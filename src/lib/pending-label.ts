/** "Save changes" becomes "Saving changes…". Returns null when the first word is not a known verb. */
export function pendingLabel(label: string): string | null {
	const match = /^(\s*)(\S+)(.*)$/s.exec(label);
	const gerund = match ? GERUNDS[match[2].toLowerCase()] : undefined;
	if (!match || !gerund) return null;
	return `${match[1]}${gerund}${match[3].trimEnd()}…`;
}
